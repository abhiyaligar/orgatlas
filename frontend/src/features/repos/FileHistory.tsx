import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { useFileDescription, useFileTimeline } from "@/hooks/useOrgAtlasData";
import { ErrorState, LoadingState } from "@/components/shared/RequestStates";
import { Badge } from "@/components/ui/badge";

/**
 * File history and the description the backend derived for it.
 *
 * The description is shown with its provenance rather than as a bare summary,
 * so a reader can tell an authored docstring apart from a generated one and
 * whether it has drifted from the current code.
 */
export function FileHistory({ fileId }: { fileId: string }) {
  const timeline = useFileTimeline(fileId);
  const description = useFileDescription(fileId);

  return (
    <div className="grid gap-4 lg:grid-cols-2">
      <Card>
        <CardHeader>
          <CardTitle className="text-base">
            {timeline.data?.path ?? "File history"}
          </CardTitle>
        </CardHeader>
        <CardContent className="space-y-3">
          {timeline.state === "loading" ? <LoadingState label="Loading history" /> : null}
          {timeline.state === "error" && timeline.failure ? (
            <ErrorState failure={timeline.failure} onRetry={timeline.reload} />
          ) : null}
          {timeline.data ? (
            <>
              <p className="text-xs text-muted-foreground">
                {timeline.data.change_count} changes by{" "}
                {timeline.data.contributors.length} contributor
                {timeline.data.contributors.length === 1 ? "" : "s"}
              </p>
              <ol className="space-y-2">
                {timeline.data.history.map((commit) => (
                  <li key={commit.sha} className="space-y-0.5 border-b border-border pb-2 last:border-0">
                    <div className="flex flex-wrap items-center gap-2">
                      <code className="text-xs">{commit.sha.slice(0, 7)}</code>
                      <span className="text-sm">{commit.message}</span>
                    </div>
                    <p className="text-xs text-muted-foreground">{commit.author}</p>
                  </li>
                ))}
              </ol>
            </>
          ) : null}
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle className="text-base">Description</CardTitle>
        </CardHeader>
        <CardContent className="space-y-3">
          {description.state === "loading" ? <LoadingState label="Loading description" /> : null}
          {description.state === "error" && description.failure ? (
            <ErrorState failure={description.failure} onRetry={description.reload} />
          ) : null}
          {description.data ? (
            <>
              <p className="text-sm">{description.data.summary}</p>
              <div className="flex flex-wrap gap-2">
                <Badge
                  variant={
                    description.data.provenance.origin === "generated" ? "warning" : "success"
                  }
                >
                  {description.data.provenance.origin}
                </Badge>
                {description.data.stale ? <Badge variant="warning">stale</Badge> : null}
                <Badge variant="outline">{description.data.language}</Badge>
                {description.data.is_test ? <Badge variant="outline">test</Badge> : null}
              </div>
              {description.data.provenance.origin === "generated" ? (
                <p className="text-xs text-muted-foreground">
                  generated by {description.data.provenance.model} at{" "}
                  {description.data.provenance.generated_at}
                </p>
              ) : null}
              {description.data.symbols.length > 0 ? (
                <div className="space-y-1">
                  <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                    Declared symbols
                  </p>
                  <ul className="flex flex-wrap gap-2">
                    {description.data.symbols.map((symbol) => (
                      <li key={symbol}>
                        <Badge variant="outline">{symbol}</Badge>
                      </li>
                    ))}
                  </ul>
                </div>
              ) : null}
            </>
          ) : null}
        </CardContent>
      </Card>
    </div>
  );
}